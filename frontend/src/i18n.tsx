const dictionaries: Record<Lang, Record<Key, string>> = {uk, en, de, ru}

export const LANGS: Array<{code: Lang; label: string; short: string}> = [
  {code: 'uk', label: 'Українська', short: 'УКР'},
  {code: 'en', label: 'English', short: 'ENG'},
  {code: 'de', label: 'Deutsch', short: 'DEU'},
  {code: 'ru', label: 'Русский', short: 'РУС'},
]

export type TranslationKey = Key

const LANG_STORAGE_KEY = 'readywin.lang'
const LEGACY_LANG_STORAGE_KEY = 'firstwin.lang'

function systemLang(): Lang {
  const candidates = [...(navigator.languages ?? []), navigator.language]
  for (const raw of candidates) {
    const code = (raw || '').toLowerCase()
    if (code.startsWith('uk')) return 'uk'
    if (code.startsWith('de')) return 'de'
    if (code.startsWith('ru')) return 'ru'
    if (code.startsWith('en')) return 'en'
  }
  return 'en'
}

export function initialLang(): Lang {
  const saved =
    localStorage.getItem(LANG_STORAGE_KEY) ?? localStorage.getItem(LEGACY_LANG_STORAGE_KEY)
  if (saved === 'uk' || saved === 'en' || saved === 'de' || saved === 'ru') return saved
  return systemLang()
}

type Vars = Record<string, string | number>

function interpolate(text: string, vars?: Vars): string {
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name]
    return value === undefined ? match : String(value)
  })
}

function pickForm(lang: Lang, forms: string[], count: number): string {
  const value = Math.abs(count)
  if (lang === 'uk' || lang === 'ru') {
    const mod10 = value % 10
    const mod100 = value % 100
    if (mod10 === 1 && mod100 !== 11) return forms[0]
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return forms[1] ?? forms[0]
    return forms[2] ?? forms[1] ?? forms[0]
  }
  return value === 1 ? forms[0] : forms[1] ?? forms[0]
}

type I18nValue = {
  lang: Lang
  setLang: (lang: Lang) => void
  locale: string
  /** Translate a key. `{name}` placeholders are replaced from `vars`. */
  t: (key: Key, vars?: Vars) => string
  /** Plural form of a dictionary entry that stores `one|few|many` (or `one|many`). */
  tn: (key: Key, count: number) => string
  /** `count + plural form`, ready to insert into a sentence. */
  tc: (key: Key, count: number) => string
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({children}: {children: ReactNode}) {
  const [lang, setLang] = useState<Lang>(initialLang)

  useEffect(() => {
    localStorage.setItem(LANG_STORAGE_KEY, lang)
    setFormatLang(lang)
    document.documentElement.lang = lang
  }, [lang])

  const value = useMemo<I18nValue>(() => {
    const table = dictionaries[lang]
    const t = (key: Key, vars?: Vars) => interpolate(table[key] ?? uk[key] ?? key, vars)
    const tn = (key: Key, count: number) => pickForm(lang, String(table[key] ?? uk[key] ?? '').split('|'), count)
    const tc = (key: Key, count: number) => `${count} ${tn(key, count)}`
    return {lang, setLang, locale: formatLocale(), t, tn, tc}
  }, [lang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
